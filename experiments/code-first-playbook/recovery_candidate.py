"""One fixed human section; the CAK-233 language and live owners are unchanged."""

import argparse
import copy
from pathlib import Path
import re
import sys

from compiler.load import load_modules, safe_path
from compiler.model import Invalid, canonical, digest, reference_sites, require
from compiler.validate import validate
from compiler.diff import semantic_diff
from compiler.provenance import binding, read_json, write_outputs

ROOT = Path(__file__).resolve().parent
MODULES = ['semantics/startup.yaml', 'semantics/source-retrieval.yaml']
RULE = 'pb.retrieval-recovery'
ACTION = 'action.retrieval-recovery'
OUTPUT = 'recovery.md'
OWNER = 'docs/source-first-retrieval.md'


def corpus(root=ROOT):
    modules, locations = load_modules(root, MODULES)
    records, _ = validate(modules, locations)
    return records, locations


def envelope(records):
    """Guard every dependency except the editable section body; no judgment pruning.

    Other rule owners remain external. Their records are guarded, but we do not
    traverse their execution contracts and claim to render those documents.
    """
    pending, seen = [RULE], set()
    while pending:
        rid = pending.pop()
        if rid in seen:
            continue
        seen.add(rid)
        if records[rid]['kind'] == 'rule' and rid != RULE:
            continue
        pending.extend(target for _, target in reference_sites(records[rid]))
    guarded = copy.deepcopy({rid: records[rid] for rid in sorted(seen)})
    guarded[ACTION].pop('does')
    return {rid: digest(canonical(record)) for rid, record in guarded.items()}


def section(records):
    """Only collapse blank lines separating list siblings; preserve all tokens."""
    paragraphs = records[ACTION]['does'].rstrip().split('\n\n')
    result = paragraphs[0]
    for previous, paragraph in zip(paragraphs, paragraphs[1:]):
        siblings = all(re.match(r'(?:- |[1-9][0-9]*\. )', p) for p in (previous, paragraph))
        result += ('\n' if siblings else '\n\n') + paragraph
    return result + '\n'


def render(records, contract):
    require(contract['section'] == OWNER + '#recovery', 'wrong candidate section')
    require(contract['envelope_sha256'] == envelope(records),
            'unrendered recovery envelope changed; review its section mapping before regeneration')
    return ('# Recovery\n\n'
            '<!-- Generated by make code-first-recovery-render. Do not edit this file. -->\n'
            '> Replacement candidate. [Existing prose](../../../../docs/source-first-retrieval.md#recovery) controls.\n'
            '> Edit [the semantic source](../../semantics/source-retrieval.yaml) (`action.retrieval-recovery/does`).\n\n'
            + section(records)).encode()


def generate(root=ROOT):
    records, _ = corpus(root)
    sources = read_json(root, 'provenance/sources.json')
    # This is frozen provenance, not a compile-time read of hand-maintained prose.
    binding(root, sources, records)
    contract = read_json(root, 'recovery/contract.json')
    document = render(records, contract)
    paths = MODULES + ['recovery_candidate.py', 'recovery/contract.json',
                       'requirements.txt', 'provenance/sources.json']
    paths += [str(p.relative_to(root)) for p in sorted((root / 'compiler').glob('*.py'))]
    provenance = {
        'status': 'replacement_candidate_only', 'authority_transferred': False,
        'section': contract['section'], 'body_clause': ACTION + '/does',
        'section_rule': RULE, 'envelope_sha256': envelope(records),
        'scope': 'One prose section; surrounding retrieval and authority owners remain external.',
        'source_binding': next(u for u in sources['units'] if u['unit'] == RULE),
        'inputs': {p: {'bytes': len(raw), 'sha256': digest(raw)} for p in sorted(paths)
                   for raw in [safe_path(root, p).read_bytes()]},
        'output': {'path': OUTPUT, 'bytes': len(document), 'sha256': digest(document)},
        'identity': 'Input bytes and output digest; the delivery PR binds the exact commit.',
    }
    return {OUTPUT: document, 'provenance.json': canonical(provenance)}


def compare(directory, outputs):
    require(not directory.is_symlink(), 'symlink candidate directory')
    paths = set()
    for path in directory.rglob('*'):
        require(not path.is_symlink(), 'symlink candidate output')
        if path.is_file():
            paths.add(str(path.relative_to(directory)))
    require(paths == set(outputs), 'missing or extra candidate output')
    for path, raw in outputs.items():
        require(safe_path(directory, path).read_bytes() == raw,
                'stale_or_hand_edited: ' + path)


def definition_probe(records, locations):
    """A hypothetical edit exercises the existing semantic diff, not new policy."""
    changed = copy.deepcopy(records)
    changed[ACTION]['does'] += '\nSIMULATION: Record the correction location for mock review.\n'
    report = semantic_diff(records, changed, locations, locations)
    # The shared diff names the historic pilot outputs. Add only this consumer's
    # concrete affected path; leave its classifications and fan-out untouched.
    return {'simulation_only': True, 'shared_semantic_diff': report,
            'candidate_effects': [
                {'event': event['id'], 'output': 'recovery/generated/' + OUTPUT,
                 'effect': 'body_changed' if event['id'] == ACTION else 'envelope_review_required'}
                for event in report['events'] if RULE in event['affected_rules']]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['render', 'check', 'source-check', 'diff'])
    args = parser.parse_args()
    try:
        if args.command in ('render', 'check'):
            outputs = generate()
            if args.command == 'render':
                write_outputs(ROOT / 'recovery/generated', outputs)
            else:
                compare(ROOT / 'recovery/generated', outputs)
            result = {'status': 'generated_candidate' if args.command == 'render' else 'byte_identical',
                      'files': sorted(outputs), 'authority_transferred': False}
        elif args.command == 'source-check':
            records, _ = corpus()
            result = binding(ROOT, read_json(ROOT, 'provenance/sources.json'), records, ROOT.parents[1])
            require(not result['changes'], 'current prose bindings drifted: ' + str(result['changes']))
            prose = safe_path(ROOT.parents[1], OWNER).read_text()
            body = prose.split('\n## Recovery\n\n', 1)[1].split('\n## ', 1)[0].strip()
            require(section(records).strip() == body, 'Recovery section parity failed')
            result['recovery_section_parity'] = 'exact_after_list_spacing'
        else:
            result = definition_probe(*corpus())
        print(canonical(result).decode(), end='')
        return 0
    except (Invalid, OSError, ValueError, KeyError, TypeError, IndexError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
